module ScrabbleScore

open System

let private letterScore =
    function
    | 'D' | 'G' -> 2
    | 'B' | 'C' | 'M' | 'P' -> 3
    | 'F' | 'H' | 'V' | 'W' | 'Y' -> 4
    | 'K' -> 5
    | 'J' | 'X' -> 8
    | 'Q' | 'Z' -> 10
    | _ -> 1

let score word = word |> Seq.sumBy (Char.ToUpper >> letterScore)
